sample_rate = 48000
speaker = 'eugene'

# Pause durations (in seconds)
sentence_pause_sec = 0.3
paragraph_pause_sec = 0.8

sentence_pause = np.zeros(int(sample_rate * sentence_pause_sec))
paragraph_pause = np.zeros(int(sample_rate * paragraph_pause_sec))

paragraphs = text.strip().split('\n')
paragraphs = [p.strip() for p in paragraphs if p.strip()]

# Pitch and speed
pitch_steps = 1
speed_rate = 1

audio_chunks = []
timings = []        # list of {sentence, start_sec, end_sec}
cursor_samples = 0  # tracks position in raw audio before librosa

for paragraph in paragraphs:
    sentences = re.split(r'(?<=[.!?…])\s+', paragraph.strip())
    sentences = [s.strip() for s in sentences if s.strip()]

    for sentence in sentences:
        print(f"Generating: {sentence[:50]}...")
        audio = model.apply_tts(text=sentence, speaker=speaker, sample_rate=sample_rate)
        chunk = audio.numpy()

        start_sample = cursor_samples
        cursor_samples += len(chunk)

        timings.append({
            "sentence": sentence,
            "start_sample": start_sample,
            "end_sample": cursor_samples,
        })

        audio_chunks.append(chunk)
        audio_chunks.append(sentence_pause)
        cursor_samples += len(sentence_pause)

    audio_chunks.append(paragraph_pause)
    cursor_samples += len(paragraph_pause)

full_audio = np.concatenate(audio_chunks)
raw_total_samples = len(full_audio)

final_total_samples = len(full_audio)

# Scale all timestamps to match the stretched audio duration
for t in timings:
    t["start_sec"] = round((t["start_sample"] / raw_total_samples) * (final_total_samples / sample_rate), 4)
    t["end_sec"]   = round((t["end_sample"]   / raw_total_samples) * (final_total_samples / sample_rate), 4)
    del t["start_sample"]
    del t["end_sample"]

# Save audio
sf.write('output.wav', full_audio, sample_rate)
print("Done! Saved to output.wav")

# Save timings
with open('timings.json', 'w', encoding='utf-8') as f:
    json.dump(timings, f, ensure_ascii=False, indent=2)
print(f"Saved timings.json with {len(timings)} sentences")